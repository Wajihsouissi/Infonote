import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';

const base = process.env.RESEARCH_TEST_URL || 'http://127.0.0.1:5198';
const output = 'design/research-cut/review';
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.goto(`${base}/website3test/`);
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(1100);
  const scene = page.locator('#cut [data-scene]');
  const bounds = await scene.evaluate(el => ({ top: el.getBoundingClientRect().top + scrollY, height: el.offsetHeight }));
  const piece = page.locator('#cut [data-piece]').nth(1);
  const go = async y => { await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), y); await page.waitForTimeout(900); };
  const pose = () => piece.evaluate(el => getComputedStyle(el).transform);
  await go(bounds.top - 820);
  const from = await pose();
  await go(bounds.top - 580);
  assert.equal(await pose(), from, 'Extraction must wait until the scene is clearly in view');
  await page.screenshot({ path: `${output}/desktop-cut-before.png` });
  await go(bounds.top - 110);
  const to = await pose();
  await page.screenshot({ path: `${output}/desktop-cut-after.png` });
  assert.notEqual(from, to, 'The extracted idea must move from the source note');
  await go(bounds.top - 820);
  const reverse = await pose();
  const values = matrix => matrix.match(/[-\d.]+/g).map(Number);
  const first = values(from); const restored = values(reverse);
  first.forEach((value, index) => assert(Math.abs(value - restored[index]) < .1, 'Reverse scroll restores the original source pose'));
  await fs.writeFile(`${output}/motion-check.json`, JSON.stringify({ from, to, reverse, waitsForViewport: true, reversible: true }, null, 2));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(500);
  const lowerPanel = page.locator('#assist [data-piece]').nth(1);
  const panelTop = await lowerPanel.evaluate(el => el.getBoundingClientRect().top + scrollY);
  await go(panelTop - 844 * .9);
  const mobileBefore = await lowerPanel.evaluate(el => getComputedStyle(el).transform);
  await go(panelTop - 844 * .8);
  assert.equal(await lowerPanel.evaluate(el => getComputedStyle(el).transform), mobileBefore, 'The lower mobile panel waits for its own viewport entry');
  await go(panelTop - 844 * .3);
  const mobileAfter = await lowerPanel.evaluate(el => getComputedStyle(el).transform);
  assert.notEqual(mobileBefore, mobileAfter, 'The mobile panel animates while it is visible');
  await fs.writeFile(`${output}/motion-check.json`, JSON.stringify({ from, to, reverse, waitsForViewport: true, reversible: true, mobileBefore, mobileAfter, mobileWaitsForViewport: true }, null, 2));
  const cards = page.locator('#explore button[aria-pressed]');
  await cards.nth(0).click(); await cards.nth(1).click();
  await page.getByRole('button', { name: 'Connect ideas', exact: true }).click();
  await page.getByRole('list', { name: 'Your connections' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/mobile-connected-pair.png` });
  await page.getByRole('button', { name: 'Open this idea' }).click();
  await page.locator('#depth').evaluate(el => window.scrollTo({ top: el.offsetTop - 95, behavior: 'instant' }));
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${output}/mobile-depth-open.png` });
  await page.setViewportSize({ width: 360, height: 800 });
  await page.locator('#depth').evaluate(el => window.scrollTo({ top: el.offsetTop - 95, behavior: 'instant' }));
  await page.screenshot({ path: `${output}/compact-depth-open.png` });
  console.log('Extraction and reverse scroll verified; mobile connection and nested canvas captured.');
} finally { await browser.close(); }
